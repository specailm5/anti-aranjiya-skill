def scan_text(text: str) -> List[Dict]:
    """فحص النص واستخراج كافة مواضع العرنجية مع أرقام الأسطر والبدائل"""
    findings = []
    lines = text.splitlines()

    for line_idx, line in enumerate(lines, start=1):
        for rule in RULES:
            matches = list(re.finditer(rule["pattern"], line))
            for m in matches:
                findings.append({
                    "line": line_idx,
                    "matched": m.group(0),
                    "start": m.start(),
                    "end": m.end(),
                    "id": rule["id"],
                    "category": rule["category"],
                    "message": rule["message"],
                    "replacement": rule["replacement"],
                    "context": line.strip()
                })
    return findings

