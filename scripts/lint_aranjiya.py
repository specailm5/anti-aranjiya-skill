def main():
    parser = argparse.ArgumentParser(description="مدقق العرنجية للنصوص والترجمات العربية")
    parser.add_argument("file", nargs="?", help="مسار الملف المراد فحصه")
    parser.add_argument("--text", "-t", help="نص مباشر للفحص بين علامتي تنصيص")
    args = parser.parse_args()

    content = ""
    if args.text:
        content = args.text
    elif args.file:
        try:
            with open(args.file, "r", encoding="utf-8") as f:
                content = f.read()
        except Exception as e:
            print(f"خطأ في قراءة الملف: {e}", file=sys.stderr)
            sys.exit(1)
    else:
        # قراءة من الإدخال القياسي إذا لم يُحدد ملف
        if not sys.stdin.isatty():
            content = sys.stdin.read()
        else:
            parser.print_help()
            sys.exit(0)

    findings = scan_text(content)
    print_report(findings, len(content.splitlines()))

    # الخروج برمز خطأ 1 إذا وُجدت ملاحظات، للربط مع CI/CD و Git Hooks
    if findings:
        sys.exit(1)
    else:
        sys.exit(0)

if __name__ == "__main__":
    main()
