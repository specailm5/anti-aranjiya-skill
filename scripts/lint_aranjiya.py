    print(f"\n⚠️  تم العثور على {len(findings)} موضعاً من مواضع العجمة والعرنجية:\n")

    for idx, f in enumerate(findings, start=1):
        print(f"[{idx}] سطر {f['line']} | باب: {f['category']}")
        print(f"    ❌ اللفظ/التركيب المرصود: «{f['matched']}»")
        print(f"    🔍 العلة: {f['message']}")
        print(f"    ✅ الصواب الفصيح: {f['replacement']}")
        print(f"    📄 السياق: \"{f['context']}\"")
        print("-" * 70)

    print(f"\n📊 إجمالي الملاحظات: {len(findings)} موضعاً في {total_lines} سطراً.")
